import Foundation

// Generate the ignored build input without placing secrets in arguments or logs.
let environment = ProcessInfo.processInfo.environment
let variables = [
    ("appKey", "DROPBOX_APP_KEY"),
    ("appSecret", "DROPBOX_APP_SECRET"),
    ("refreshToken", "DROPBOX_REFRESH_TOKEN")
]

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data(("error: " + message + "\n").utf8))
    exit(1)
}

guard let repository = environment["CI_PRIMARY_REPOSITORY_PATH"], !repository.isEmpty else {
    fail("CI_PRIMARY_REPOSITORY_PATH is required. This script is for Xcode Cloud.")
}

var declarations: [String] = []
for (property, variable) in variables {
    guard let value = environment[variable],
          !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
          !value.hasPrefix("YOUR-") else {
        fail("Set \(variable) as a secret environment variable in the Xcode Cloud workflow.")
    }
    // Scalar escapes safely preserve quotes, backslashes, Unicode, and newlines.
    let literal = value.unicodeScalars.map { "\\u{\(String($0.value, radix: 16))}" }.joined()
    declarations.append("    static let \(property) = \"\(literal)\"")
}

let destination = URL(fileURLWithPath: repository, isDirectory: true)
    .appendingPathComponent("MagnumFieldTraining/Sync/StagingCredentials.local.swift")
let source = "// Generated by Xcode Cloud. Do not commit.\nenum StagingCredentials {\n"
    + declarations.joined(separator: "\n") + "\n}\n"
do {
    try source.write(to: destination, atomically: true, encoding: .utf8)
    try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: destination.path)
} catch {
    fail("Could not generate the Dropbox credentials build input. Check the repository path and file permissions.")
}
print("Generated the Dropbox credentials build input.")
